/** 按关键词过滤（探索页搜索态用） */
export const searchCards = (kw) => {
  if (!kw) return []
  const s = kw.toLowerCase()
  return KNOWLEDGE_CARDS.filter(
    (x) => x.title.toLowerCase().includes(s) || x.summary.toLowerCase().includes(s) || x.tag.includes(s)
  )
}

/** 今日一识：按日期稳定轮换 */
export const dailyCard = () => {
  const d = new Date()
  const seed = d.getFullYear() * 372 + (d.getMonth() + 1) * 31 + d.getDate()
  return KNOWLEDGE_CARDS[seed % KNOWLEDGE_CARDS.length]
}
